-- Prepare shared storage; the application still uses SQLite until its adapter is added.
BEGIN;
CREATE TABLE public.pioneers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    category text,
    achievement text DEFAULT '',
    biography text DEFAULT '',
    project_title text NOT NULL DEFAULT 'Black Pioneers: First in American History',
    folder_path text DEFAULT '',
    created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS'),
    updated_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS'),
    UNIQUE (name, project_title)
);
COMMENT ON COLUMN public.pioneers.folder_path IS 'Legacy local path retained for migration; never use as a cross-machine media location.';
CREATE INDEX pioneers_project_created_idx ON public.pioneers (project_title, created_at DESC, id DESC);

CREATE TABLE public.pioneer_media (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    pioneer_id bigint NOT NULL REFERENCES public.pioneers(id) ON DELETE RESTRICT,
    kind text NOT NULL CHECK (kind IN ('image', 'audio', 'video')),
    bucket_id text NOT NULL DEFAULT 'pioneer-media',
    object_path text NOT NULL CHECK (length(object_path) > 0 AND left(object_path, 1) <> '/'),
    original_filename text NOT NULL,
    content_type text,
    size_bytes bigint CHECK (size_bytes >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (bucket_id, object_path)
);
CREATE INDEX pioneer_media_pioneer_kind_idx ON public.pioneer_media (pioneer_id, kind);
COMMENT ON TABLE public.pioneer_media IS 'Index of Storage objects; file bytes live in the private pioneer-media bucket.';

-- No anonymous or general authenticated write access. A future app adapter must
-- use restricted authorization before shared writes are exposed to visitors.
ALTER TABLE public.pioneers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pioneer_media ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pioneers, public.pioneer_media FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.pioneers_id_seq FROM anon, authenticated;
GRANT ALL ON public.pioneers, public.pioneer_media TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.pioneers_id_seq TO service_role;
COMMIT;
